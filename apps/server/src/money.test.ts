describe("money in what the user writes", () => {
  for (const [text, values] of [...TURKISH, ...ENGLISH, ...MORE])
    test(text.replace(/\n/g, " / "), () => expect(found(text)).toEqual(values));
  for (const text of [...NOT_MONEY, ...MORE_NOT_MONEY])
    test(`not money: ${text}`, () => expect(found(text)).toEqual([]));
});

describe("a saved figure", () => {
  test("is hidden in every form it is written again in, and only there", () => {
    const values = [
      { name: "maas", value: "85.000 TL" },
      { name: "fiyat", value: "€300" },
      { name: "kira", value: "25000" },
    ];
    const hide = (text: string) => hidePrivate(text, values).text;
    expect(hide("Maaşım 85.000 TL'dir")).toBe("Maaşım [[private:maas]]'dir");
    expect(hide("€300 geldi, €3000 değil, €300.50 değil")).toBe("[[private:fiyat]] geldi, €3000 değil, €300.50 değil");
    expect(hide("kira 25000, port 125000 ve 25000.5")).toBe("kira [[private:kira]], port 125000 ve 25000.5");
  });

  test("found in a message is the text the guard saves, so it is hidden there", () => {
    for (const [text] of [...TURKISH, ...ENGLISH, ...MORE]) {
      const shapes = findPrivateShapes(text);
      const values = shapes.map((s, i) => ({ name: `v${i}`, value: s.value }));
      const hidden = hidePrivate(text, values).text;
      for (const s of shapes) expect(hidden).not.toContain(s.value);
    }
  });
});
